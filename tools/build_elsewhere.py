#!/usr/bin/env python3
"""Checks elsewhere.json (wheel models published by the makers or the community, linked rather than hosted here)
and writes ELSEWHERE.md from it.

  python tools/build_elsewhere.py            write ELSEWHERE.md
  python tools/build_elsewhere.py --check    fail when ELSEWHERE.md is out of date or an entry is invalid (CI)

Standard library only.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'elsewhere.json')
OUT = os.path.join(ROOT, 'ELSEWHERE.md')
REQUIRED = {'id': str, 'name': str, 'maker': str, 'kind': str, 'author': str, 'url': str, 'files': str, 'model': str,
            'license': str, 'rehost': bool, 'notes': str, 'checked': str}
OPTIONAL = {'licenseText': str, 'signIn': (bool, type(None))}
KINDS = ('maker', 'community')
MODELS = {'cad': 'CAD', 'full': '3D model', 'printable': '3D print'}
LICENSES = {'CC0-1.0': 'CC0 (public domain)', 'CC-BY-4.0': 'CC BY 4.0', 'CC-BY-SA-4.0': 'CC BY-SA 4.0',
            'CC-BY-NC-4.0': 'CC BY-NC 4.0', 'CC-BY-NC-SA-4.0': 'CC BY-NC-SA 4.0', 'CC-BY-NC-ND-4.0': 'CC BY-NC-ND 4.0',
            'All rights reserved': 'All rights reserved'}
OPEN = ('CC0-1.0', 'CC-BY-4.0')   # licences that let us host a converted copy in wheels/

problems = []

def load():
    try:
        data = json.load(open(SRC, encoding='utf-8'))
    except ValueError as e:
        sys.exit(f'elsewhere.json: {e}')
    if data.get('schema') != 1 or not isinstance(data.get('wheels'), list):
        sys.exit('elsewhere.json: needs "schema": 1 and a "wheels" list')
    seen = set()
    for w in data['wheels']:
        wid = w.get('id', '?')
        for k, t in REQUIRED.items():
            if not isinstance(w.get(k), t):
                problems.append(f'{wid}: "{k}" missing or not {t.__name__}')
        for k in w:
            if k not in REQUIRED and k not in OPTIONAL:
                problems.append(f'{wid}: unknown field "{k}"')
        if not re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', str(wid)):
            problems.append(f'{wid}: "id" must be kebab-case')
        if wid in seen:
            problems.append(f'{wid}: duplicate id')
        seen.add(wid)
        if not str(w.get('url', '')).startswith('https://'):
            problems.append(f'{wid}: "url" must be https')
        if w.get('kind') not in KINDS:
            problems.append(f'{wid}: "kind" must be one of {KINDS}')
        if w.get('model') not in MODELS:
            problems.append(f'{wid}: "model" must be one of {tuple(MODELS)}')
        if w.get('license') not in LICENSES:
            problems.append(f'{wid}: "license" must be one of {tuple(LICENSES)}')
        if w.get('rehost') and w.get('license') not in OPEN + ('CC-BY-SA-4.0',):
            problems.append(f'{wid}: "rehost" true needs an open licence')
        if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', str(w.get('checked', ''))):
            problems.append(f'{wid}: "checked" must be a date, YYYY-MM-DD')
    return data

def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')

def render(data):
    ws = data['wheels']
    makers = sorted((w for w in ws if w['kind'] == 'maker'), key=lambda w: (w['maker'], w['name']))
    community = sorted((w for w in ws if w['kind'] == 'community'),
                       key=lambda w: (w['license'] not in OPEN, w['maker'] == 'DIY', w['name']))
    def row(w):
        lic = LICENSES[w['license']]
        sign = ' Sign-in needed.' if w.get('signIn') else ''
        return (f"| [{cell(w['name'])}]({w['url']}) | {cell(w['author'])} | {MODELS[w['model']]}: {cell(w['files'])} | "
                f"{lic} | {cell(w['notes'])}{sign} |")
    head = '| Wheel | By | Files | Licence | Notes |\n|---|---|---|---|---|'
    none = data.get('none', {})
    out = [
        '# Wheel models elsewhere',
        '',
        '<!-- Generated by tools/build_elsewhere.py from elsewhere.json. Edit the JSON, then run the script. -->',
        '',
        'Wheel models you can download from the wheel makers or other sites. They are not hosted here: most of them',
        "have a licence that doesn't allow it, so download them from the link and keep them for your own use.",
        'Ready-to-use models for Virtual Real Cockpit are in [index.json](index.json) and in the app under',
        '*Get a wheel…*.',
        '',
        'Licences and links were checked by hand on the date in `elsewhere.json`. If one has moved or changed, open an',
        'issue.',
        '',
        '## From the wheel makers',
        '',
        head,
        *[row(w) for w in makers],
        '',
    ]
    if any(w['license'] == 'All rights reserved' for w in makers):
        out += ['Simucube\'s terms, on the download page: "' + next(w['licenseText'] for w in makers if w.get('licenseText')) +
                '" So download them for yourself; please don\'t share or re-upload them.', '']
    out += [
        '## From the community',
        '',
        'Models made by fans or DIY builders. The CC BY and CC0 ones can be converted and added to this library',
        '(see [CONTRIBUTING.md](CONTRIBUTING.md)); the others are for your own use only.',
        '',
        head,
        *[row(w) for w in community],
        '',
    ]
    if none:
        out += [
            '## Makers without 3D files',
            '',
            f"No official 3D model of their wheels as of {none.get('checked', '?')}: {', '.join(none.get('makers', []))}. "
            f"{none.get('notes', '')} If one of them publishes a model, open an issue.",
            '',
        ]
    out += [
        '## Use one in Virtual Real Cockpit',
        '',
        'The app loads `.glb`, `.gltf`, `.fbx`, `.obj` and `.zip` (Wheel › model select › *Load your own model…*).',
        '',
        '- **STEP or IGES** (CAD): open it in [FreeCAD](https://www.freecad.org) (free), select the parts, then',
        '  File › Export › glTF. CAD files are often millions of triangles: reduce them in Blender (Decimate modifier)',
        '  to under 300k.',
        '- **STL**: import it in [Blender](https://www.blender.org) (free) and export as glTF Binary (.glb).',
        '- Then set it up as the manual\'s *Scan your wheel* chapter shows: hub at the origin, facing you, real size.',
        '  The app also has a *Pivot* and *Scale* in Wheel › MODEL and ROTATION.',
        '',
        'Wheel makers\' names and logos are the trademarks of their owners. Models by fans are not endorsed by the',
        'makers.',
        '',
    ]
    return '\n'.join(out)

def main():
    data = load()
    text = render(data)
    if problems:
        print('\n'.join(problems))
        sys.exit(1)
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current.replace('\r\n', '\n') != text:
            sys.exit('ELSEWHERE.md is out of date: run python tools/build_elsewhere.py')
        print(f'elsewhere.json: {len(data["wheels"])} entries, ELSEWHERE.md up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote ELSEWHERE.md: {len(data["wheels"])} entries')

if __name__ == '__main__':
    main()
