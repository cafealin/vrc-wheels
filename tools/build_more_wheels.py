#!/usr/bin/env python3
"""Checks more-wheels.json (wheel models from the makers or the community, linked rather than hosted here) and
writes MORE-WHEELS.md from it.

  python tools/build_more_wheels.py            write MORE-WHEELS.md
  python tools/build_more_wheels.py --check    fail when MORE-WHEELS.md is out of date or an entry is invalid (CI)

Standard library only.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'more-wheels.json')
OUT = os.path.join(ROOT, 'MORE-WHEELS.md')
REQUIRED = {'id': str, 'name': str, 'maker': str, 'kind': str, 'author': str, 'url': str, 'files': str, 'model': str,
            'license': str, 'rehost': bool, 'notes': str, 'checked': str}
OPTIONAL = {'licenseText': str, 'signIn': (bool, type(None))}
KINDS = ('maker', 'community')
MODELS = {'cad': 'CAD', 'full': '3D model', 'printable': '3D print'}
LICENSES = {'CC0-1.0': 'CC0 (public domain)', 'CC-BY-4.0': 'CC BY 4.0', 'CC-BY-SA-4.0': 'CC BY-SA 4.0',
            'CC-BY-NC-4.0': 'CC BY-NC 4.0', 'CC-BY-NC-SA-4.0': 'CC BY-NC-SA 4.0', 'CC-BY-NC-ND-4.0': 'CC BY-NC-ND 4.0',
            'All rights reserved': 'All rights reserved'}
OPEN = ('CC0-1.0', 'CC-BY-4.0')   # licences that let us host a converted copy in wheels/

problems = []

def load():
    try:
        data = json.load(open(SRC, encoding='utf-8'))
    except ValueError as e:
        sys.exit(f'more-wheels.json: {e}')
    if data.get('schema') != 1 or not isinstance(data.get('wheels'), list):
        sys.exit('more-wheels.json: needs "schema": 1 and a "wheels" list')
    seen = set()
    for w in data['wheels']:
        wid = w.get('id', '?')
        for k, t in REQUIRED.items():
            if not isinstance(w.get(k), t):
                problems.append(f'{wid}: "{k}" missing or not {t.__name__}')
        for k in w:
            if k not in REQUIRED and k not in OPTIONAL:
                problems.append(f'{wid}: unknown field "{k}"')
        if not re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', str(wid)):
            problems.append(f'{wid}: "id" must be kebab-case')
        if wid in seen:
            problems.append(f'{wid}: duplicate id')
        seen.add(wid)
        if not str(w.get('url', '')).startswith('https://'):
            problems.append(f'{wid}: "url" must be https')
        if w.get('kind') not in KINDS:
            problems.append(f'{wid}: "kind" must be one of {KINDS}')
        if w.get('model') not in MODELS:
            problems.append(f'{wid}: "model" must be one of {tuple(MODELS)}')
        if w.get('license') not in LICENSES:
            problems.append(f'{wid}: "license" must be one of {tuple(LICENSES)}')
        if w.get('rehost') and w.get('license') not in OPEN + ('CC-BY-SA-4.0',):
            problems.append(f'{wid}: "rehost" true needs an open licence')
        if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', str(w.get('checked', ''))):
            problems.append(f'{wid}: "checked" must be a date, YYYY-MM-DD')
    return data

def cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')

def render(data):
    ws = data['wheels']
    makers = sorted((w for w in ws if w['kind'] == 'maker'), key=lambda w: (w['maker'], w['name']))
    community = sorted((w for w in ws if w['kind'] == 'community'),
                       key=lambda w: (w['license'] not in OPEN, w['maker'] == 'DIY', w['name']))
    def row(w):
        lic = LICENSES[w['license']]
        sign = ' You need an account to download it.' if w.get('signIn') else ''
        return (f"| [{cell(w['name'])}]({w['url']}) | {cell(w['author'])} | {MODELS[w['model']]}: {cell(w['files'])} | "
                f"{lic} | {cell(w['notes'])}{sign} |")
    head = '| Wheel | Made by | What you get | Licence | Good to know |\n|---|---|---|---|---|'
    none = data.get('none', {})
    out = [
        '# More wheel models',
        '',
        '<!-- Generated by tools/build_more_wheels.py from more-wheels.json. Edit the JSON, then run the script. -->',
        '',
        "Not every wheel can live in this repo. A few makers share 3D files of their own wheels but don't let anyone",
        're-upload them, and plenty of fans have modelled wheels under their own licences. This page collects the ones',
        'we know about, so you can grab them straight from the source.',
        '',
        'Want one that just works in Virtual Real Cockpit? Those are in the app under *Get a wheel…* (and listed in',
        '[index.json](index.json)).',
        '',
        "Spotted a wheel that's missing, or a dead link? [Open an issue](https://github.com/cafealin/vrc-wheels/issues) and we'll add it.",
        '',
        '## Straight from the wheel makers',
        '',
        head,
        *[row(w) for w in makers],
        '',
    ]
    if any(w['license'] == 'All rights reserved' for w in makers):
        out += ["Simucube says the files are theirs and need permission to share, so download them for yourself and",
                "please don't pass them on or re-upload them.", '']
    out += [
        '## Made by the community',
        '',
        'Wheels modelled by fans and DIY builders. The CC BY and CC0 ones can be cleaned up and added to the library',
        '(see [CONTRIBUTING.md](CONTRIBUTING.md)); the rest are for your own use.',
        '',
        head,
        *[row(w) for w in community],
        '',
    ]
    if none:
        out += [
            '## No 3D files yet',
            '',
            f"We couldn't find 3D models of these makers' wheels ({none.get('checked', '?')}): {', '.join(none.get('makers', []))}. "
            f"{none.get('notes', '')} If one of them puts files out, let us know.",
            '',
        ]
    out += [
        '## Getting one into Virtual Real Cockpit',
        '',
        'The app loads `.glb`, `.gltf`, `.fbx`, `.obj` and `.zip` files (Wheel › model select › *Load your own model…*).',
        '',
        '- **STEP or IGES** (CAD files): open it in [FreeCAD](https://www.freecad.org) (free), select the parts and use',
        '  File › Export › glTF. CAD models are often millions of triangles, so slim it down in Blender (Decimate',
        '  modifier) to under 300k.',
        '- **STL**: import it into [Blender](https://www.blender.org) (free) and export it as glTF Binary (.glb).',
        "- Then line it up the way the manual's *Scan your wheel* chapter shows: hub at the centre, facing you, real",
        '  size. The app has *Pivot* and *Scale* settings too (Wheel › MODEL and ROTATION).',
        '',
        "Wheel makers' names and logos belong to them. Fan-made models aren't endorsed by the makers.",
        '',
    ]
    return '\n'.join(out)

def main():
    data = load()
    text = render(data)
    if problems:
        print('\n'.join(problems))
        sys.exit(1)
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current.replace('\r\n', '\n') != text:
            sys.exit('MORE-WHEELS.md is out of date: run python tools/build_more_wheels.py')
        print(f'more-wheels.json: {len(data["wheels"])} entries, MORE-WHEELS.md up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote MORE-WHEELS.md: {len(data["wheels"])} entries')

if __name__ == '__main__':
    main()
